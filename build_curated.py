for title, author, lines, typ in CURATED:
    title = conv(title); author = conv(author)
    lines = [conv(l) for l in lines]
    key = (title, author, lines[0])
    if key in existing_keys:
        continue
    base.append({"title": title, "author": author, "lines": lines,
                 "type": typ, "diff": len(lines)})
    existing_keys.add(key); added += 1

