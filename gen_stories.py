# ============ 输出 JS 文件 ============
lines = ["/* 识字故事库 - 自动生成，共 %d 篇 */" % len(STORIES)]
lines.append("/* 由 gen_stories.py 生成 */")
lines.append(";(function(){")
lines.append("  var extra = [")
for title, text, chars in STORIES:
    # 转义引号
    title_js = title.replace('"', '\\"')
    text_js = text.replace('"', '\\"')
    seen = set()
    parts = []
    for c in chars:
        ch = c[0].replace('"', '\\"')
        if ch in seen:  # 同一故事内去重
            continue
        seen.add(ch)
        py = c[1].replace('"', '\\"') if len(c) > 1 else ""
        mean = c[2].replace('"', '\\"') if len(c) > 2 else ""
        parts.append('{char:"%s",py:"%s",mean:"%s"}' % (ch, py, mean))
    chars_js = ",".join(parts)
    lines.append('    {title:"%s",text:"%s",newChars:[%s]},' % (title_js, text_js, chars_js))
lines.append("  ];")
lines.append("  if (window.Data && window.Data.STORIES) {")
lines.append("    var existing = new Set(window.Data.STORIES.map(function(s){return s.title}));")
lines.append("    extra.forEach(function(s){ if(!existing.has(s.title)) window.Data.STORIES.push(s); });")
lines.append("  }")
lines.append("})();")

outpath = os.path.join(ROOT, "assets", "stories_data.js")
with open(outpath, "w", encoding="utf-8") as f:
    f.write("\n".join(lines))

# 统计
all_chars = set()
for _, _, chars in STORIES:
    for c in chars:
        all_chars.add(c[0])
